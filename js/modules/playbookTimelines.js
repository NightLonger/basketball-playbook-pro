/**
 * Сценарные таймлайны для комбинаций Playbook.
 *
 * Формат:
 * - duration — длительность розыгрыша в мс;
 * - initialPlayers — стартовые позиции (порядок = индекс дорожки в tracks);
 * - tracks[i] — ключевые кадры { t, x, y } для i-го игрока/мяча;
 * - drawings — события рисования: pass, arrow, screen, wavy, shot, label.
 *
 * Координаты — в системе viewBox площадки 150×280.
 * Верхнее кольцо: (75, 7.5), нижнее: (75, 272.5).
 * Трёхочковая дуга сверху проходит примерно через y = 75–85,
 * усы и углы — x = 10–20 / 130–140.
 */

const K = (t, x, y) => ({ t, x, y });

const pass = (x1, y1, x2, y2, t0, t1) => ({
    type: 'pass', x1, y1, x2, y2, t0, t1, color: '#ffcc00'
});

const arrow = (x1, y1, x2, y2, t0, t1, color = '#007aff', strokeWidth = 0.8) => ({
    type: 'arrow', x1, y1, x2, y2, t0, t1, color, strokeWidth
});

const screen = (x1, y1, x2, y2, t0, t1) => ({
    type: 'screen', x1, y1, x2, y2, t0, t1, color: '#ff9500', strokeWidth: 1.6
});

const wavy = (d, t0, t1, color = '#af52de', strokeWidth = 0.7) => ({
    type: 'wavy', d, t0, t1, color, strokeWidth
});

const shot = (x, y, t0, t1, size = 2.2) => ({
    type: 'shot', x, y, t0, t1, color: '#ff3b30', size
});

const label = (x, y, text, t0, t1, color = '#ffffff', fontSize = 4) => ({
    type: 'label', x, y, text, t0, t1, color, fontSize
});

